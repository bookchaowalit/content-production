"""Reverse guides: a committed, generated "make it by hand" reference per tool.

A reverse guide joins three things for one tool and one benchmark program:

1. the tool's *flow* — every part labelled ``LOGIC`` (rules/code, repeatable),
   ``AI-ASSIST`` (a model proposes; always validated by a ``LOGIC`` part and
   always with a fallback) or ``HUMAN-GATE`` (a person decides);
2. the engine's own :class:`~production_trace.guide.ManualGuide` for a committed
   example input (numbered steps, real menu paths, exact values);
3. the golden outputs the guide reproduces (file name + sha256).

The text is generated and checked by a drift test (``assert_reverse_guide``);
set ``REVERSE_GUIDES_UPDATE=1`` to rewrite the committed file. See
``docs/superpowers/specs/2026-11-12-reverse-guides-and-flow-labels-design.md``.
"""

from __future__ import annotations

import difflib
import os
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from .guide import ManualGuide, render_manual_markdown

LABELS = ("LOGIC", "AI-ASSIST", "HUMAN-GATE")
UPDATE_ENV = "REVERSE_GUIDES_UPDATE"
_LABEL_TEXT = {
    "LOGIC": "กฎ/โค้ด ผลเหมือนเดิมทุกครั้ง",
    "AI-ASSIST": "AI เสนอ แล้ว LOGIC ตรวจก่อนใช้ (มีทางสำรองเสมอ)",
    "HUMAN-GATE": "คนตัดสินใจ และบันทึกไว้",
}


class FlowError(ValueError):
    """A flow or reverse-guide input is invalid; ``code`` is stable."""

    def __init__(self, code: str, detail: str = "") -> None:
        super().__init__(f"{code}: {detail}" if detail else code)
        self.code = code


@dataclass(frozen=True)
class FlowPart:
    part: str
    label: str
    engine: str
    trace_stage: str
    manual_note: str = ""
    fallback: str = ""


@dataclass(frozen=True)
class Golden:
    filename: str
    sha256: str
    note: str = ""


def validate_flow(flow: Sequence[FlowPart]) -> None:
    """Reject flows that break the LOGIC-first rules (stable ``FlowError.code``)."""

    if not flow:
        raise FlowError("flow_empty")
    for part in flow:
        if part.label not in LABELS:
            raise FlowError("flow_label_unknown", part.part)
    if not any(part.label == "LOGIC" for part in flow):
        raise FlowError("flow_no_logic")
    for index, part in enumerate(flow):
        if part.label != "AI-ASSIST":
            continue
        if not part.fallback.strip():
            raise FlowError("flow_ai_no_fallback", part.part)
        following = flow[index + 1] if index + 1 < len(flow) else None
        if following is None or following.label != "LOGIC":
            raise FlowError("flow_ai_unvalidated", part.part)


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ") or "—"


def _relative(value: str, field: str) -> str:
    if value.startswith(("/", "~")) or (len(value) > 1 and value[1] == ":"):
        raise FlowError("reverse_absolute_path", field)
    return value


def render_reverse_guide(
    *,
    tool_id: str,
    benchmark: str,
    example: str,
    regenerate: str,
    flow: Sequence[FlowPart],
    guide: ManualGuide,
    goldens: Sequence[Golden],
) -> str:
    """Render the reverse guide Markdown (deterministic, repo-relative paths only)."""

    validate_flow(flow)
    _relative(example, "example")
    ai_parts = [part for part in flow if part.label == "AI-ASSIST"]
    lines = [
        f"# Reverse guide: {tool_id} → {benchmark}",
        "",
        "<!-- generated by production_trace.reverse; do not edit by hand -->",
        "",
        f"ไฟล์นี้สร้างจาก engine โดยตรง: ทำตามขั้นตอนใน {benchmark} แล้วจะได้ผลตรงกับไฟล์อ้างอิงของเครื่องมือ",
        "",
        f"- tool: `{tool_id}`",
        f"- โปรแกรมที่ใช้ทำมือ: {benchmark}",
        f"- ตัวอย่างต้นทาง: `{example}`",
        f"- สร้างใหม่ด้วย: `{regenerate}`",
        "",
        "## Flow: ส่วนไหน logic / AI / คน",
        "",
        "| # | ส่วน | ป้าย | engine | trace stage | ทำมือ / ทางสำรอง |",
        "|---|---|---|---|---|---|",
    ]
    for index, part in enumerate(flow, start=1):
        manual = part.manual_note
        if part.fallback:
            manual = f"{manual}; ทางสำรอง: {part.fallback}" if manual else f"ทางสำรอง: {part.fallback}"
        lines.append(
            f"| {index} | {_cell(part.part)} | `{part.label}` | `{_cell(part.engine)}` | `{_cell(part.trace_stage)}` | {_cell(manual)} |"
        )
    lines += ["", *(f"- `{label}`: {text}" for label, text in _LABEL_TEXT.items())]
    if ai_parts:
        lines += [
            "",
            "เมื่อทำมือ ไม่มี AI: ส่วน `AI-ASSIST` ให้คนตัดสินใจแทนตามคอลัมน์ขวาสุด แล้วผลต้องผ่านส่วน `LOGIC` ถัดไปเหมือนเดิม",
        ]
    manual = render_manual_markdown(guide).rstrip("\n").split("\n")
    lines += ["", "---", "", *[("#" + line) if line.startswith("#") else line for line in manual]]
    lines += ["", "## ไฟล์อ้างอิง (golden)", ""]
    if goldens:
        lines += ["| ไฟล์ | sha256 | หมายเหตุ |", "|---|---|---|"]
        lines += [f"| `{_cell(_relative(golden.filename, 'golden'))}` | `{golden.sha256}` | {_cell(golden.note)} |" for golden in goldens]
    else:
        lines.append("- ไม่มีไฟล์ที่ผลซ้ำได้ทุก byte: เทียบด้วยค่าที่ตรวจในหัวข้อ 'ตรวจผล' ด้านบน")
    text = "\n".join(lines) + "\n"
    if "/home/" in text or "/tmp/" in text or "/Users/" in text:
        raise FlowError("reverse_absolute_path", "rendered text")
    return text


def assert_reverse_guide(path: str | Path, text: str) -> None:
    """Compare ``text`` with the committed guide; rewrite it when ``REVERSE_GUIDES_UPDATE=1``."""

    target = Path(path)
    if os.environ.get(UPDATE_ENV) == "1":
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        return
    if not target.is_file():
        raise AssertionError(f"{target} is missing; run with {UPDATE_ENV}=1 to write it")
    committed = target.read_text(encoding="utf-8")
    if committed != text:
        diff = "".join(
            list(difflib.unified_diff(committed.splitlines(True), text.splitlines(True), "committed", "engine"))[:40]
        )
        raise AssertionError(f"{target} drifted from the engine; review and run with {UPDATE_ENV}=1\n{diff}")


